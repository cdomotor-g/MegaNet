#!/usr/bin/env python3
"""
repeater_document.py — put every row of the original repeater document,
data/ALL_REPEATERS.csv, on the station it belongs to.

WHY THIS EXISTS
    migrate.html built Flood-Net's repeaters from that document by matching each
    row's name to a Radio Mobile unit. The match was loose, and in October 2026,
    checking the Bureau's 2024 FldWarn KMZ against Flood-Net showed what that had
    cost. Of 129 rows, 86 were on the right station, about 30 never became a
    repeater at all, and some landed on a neighbour with a similar name:

      Lower Springbrook (Gold Coast)  on Mt Lowe AL, near Emerald
      Blackdown Tableland (Emerald)   on Black Mt AL, near Gympie
      Mt Macquarie (Blackall)         on Port Macquarie (Golf), New South Wales
      Ballandean Hill                 on Ballandean AL, 1.7 km away
      Emerald Radar                   on Emerald AL, 7.5 km away
      Round Mt Res (Narangba)         on Round Mountain AL, in the Logan

    data/repeater-document.json is the reconciliation, worked out row by row
    with the evidence in its notes: each row's home station, chosen by name, ACMA
    licence site and the KMZ's paths, and what that station needs. The document
    is taken as right as of when it was written. Ranges somebody has changed
    since (Mt Kanigan, Mt Petersen, Middlemount, Florence Vale) are left as they
    are, and only their empty channel, licence or network is filled.

    Sites with two repeaters on different channels (Constitution Hill No1 and
    No2, Mt Stuart #1/#2 and #3/#4, Saddle Mountain #1 and #2) need two records,
    because a station holds one repeater. The second goes on a station already at
    the site where there is one (Constitution Hill AL); otherwise it gets a
    repeater unit of its own at the licence's ACMA site, the way Constitution
    Hill and Mt Mowbullan already are. The Baroon Dam row has no station at its
    site either. Rows listed twice with identical settings (#1 and #2) share one
    record, and the station's notes say so.

WHAT THE SQL DOES
    Adds a repeater where a station has none, its ranges only if it has none;
    fills a channel, licence, network or note only where it is empty; creates
    the three repeater units; and takes the wrong row off the six stations
    above through meganet.save_station(), the station editor's own write path.
    That is the only way a repeater's ranges are rewritten here: the same as
    unticking "repeater", or editing its ranges, in the editor. Every statement
    is guarded, so a second run changes nothing.

        python3 tools/ingest/repeater_document.py --sql \\
          | psql "$MEGANET_DB_URL" -v ON_ERROR_STOP=1 --single-transaction

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from fldwarn_kmz_2024 import q, append_note, STAMP  # noqa: E402

PLAN = os.path.join(REPO, 'data', 'repeater-document.json')
DOC_NOTES = "(doc->>'notes')"


def rep_json(p):
    return {'acma_licence': p['licence'], 'rx_mhz': p['rx'], 'tx_mhz': p['tx'], 'notes': '',
            'pass_ranges': [{'low': lo, 'high': hi} for lo, hi in p['ranges']], 'exclusions': []}


def render_sql(plan):
    S = q(STAMP)
    out = ['-- Generated by tools/ingest/repeater_document.py from data/repeater-document.json.', '']
    for p in plan['plan']:
        sid, act = q(p['home']), p['action']
        if act == 'ok':
            continue
        out.append(f"-- {', '.join(r.strip() for r in p['rows'])} → {p['home']}: {act}")
        if act == 'create':
            out.append('insert into meganet.station (id, ord, name, station_number, lat, lon, elevation_ahd, elevation_source, roles, '
                       'radio_network_ids, catchment_ids, alert_ids, satcom, rm_system_id, enabled, notes, hub_id, owner, '
                       'document_managed, updated_by)')
            out.append(f"select {sid}, (select max(ord) from meganet.station) + 1, {q(p['name'])}, '', {q(p['lat'])}, {q(p['lon'])}, "
                       f"{q(p.get('elevation_ahd'))}, {q(p.get('elevation_source'))}, array['repeater']::text[], {q(p['networks'])}, "
                       f"{q(p['catchment_ids'])}, '{{}}'::jsonb, "
                       "'{\"enabled\": false, \"provider\": \"\", \"terminal_id\": \"\"}'::jsonb, 1, true, "
                       f"{q(p['note'])}, {q(p['hub_id'])}, {q(p.get('owner'))}, true, {S}")
            out.append(f'where not exists (select 1 from meganet.station where id = {sid});')
        if act == 'replace':
            note = q(p.get('note') or "Its repeater record held the repeater document's Lower Springbrook row, attached here by the first "
                     "import's loose name match; moved to Lower Springbrook AL and replaced with this site's own row, Mt Lowe, in Oct 2026.")
            out.append('select meganet.save_station(jsonb_set(jsonb_set(jsonb_set(doc, '
                       f"'{{repeater}}', {q(json.dumps(rep_json(p)))}::jsonb), '{{radio_network_ids}}', {q(json.dumps(p['networks']))}::jsonb), "
                       f"'{{notes}}', to_jsonb({append_note(DOC_NOTES, note)})), updated_at) is not null as saved "
                       f"from meganet.station_json where id = {sid} and doc->'repeater'->>'acma_licence' = '11165505/1';")
            out.append('')
            continue
        if act in ('attach', 'fill', 'keep-edited'):
            sets, would = [], []
            if act == 'attach':
                sets.append("roles = case when 'repeater' = any(roles) then roles else roles || array['repeater'] end")
                would.append("not 'repeater' = any(roles)")
            sets.append(f"radio_network_ids = case when radio_network_ids = '{{}}' then {q(p['networks'])} else radio_network_ids end")
            would.append("radio_network_ids = '{}'")
            if p.get('note'):
                sets.append('notes = ' + append_note('notes', 'n.t'))
                would.append('position(n.t in notes) = 0')
            pre, post = (f"with n(t) as (values ({q(p['note'])})) ", ' from n') if p.get('note') else ('', '')
            out.append(f"{pre}update meganet.station set {', '.join(sets)}, updated_by = {S}{post} "
                       f"where id = {sid} and ({' or '.join(would)});")
        if act in ('attach', 'create'):
            out.append('insert into meganet.repeater (station_id, acma_licence, rx_mhz, tx_mhz, notes, updated_by) '
                       f"values ({sid}, {q(p['licence'])}, {q(p['rx'])}, {q(p['tx'])}, '', {S}) on conflict (station_id) do nothing;")
            rows = ', '.join(f"({sid}, 'pass', {lo}, {hi}, {i}, {S})" for i, (lo, hi) in enumerate(p['ranges']))
            out.append('insert into meganet.pass_range (repeater_id, kind, lo, hi, ord, updated_by) '
                       f'select * from (values {rows}) v(repeater_id, kind, lo, hi, ord, updated_by) '
                       f'where not exists (select 1 from meganet.pass_range x where x.repeater_id = {sid});')
        out.append(f"update meganet.repeater set rx_mhz = coalesce(rx_mhz, {q(p['rx'])}), tx_mhz = coalesce(tx_mhz, {q(p['tx'])}), "
                   f"acma_licence = case when acma_licence = '' then {q(p['licence'])} else acma_licence end, updated_by = {S} "
                   f"where station_id = {sid} and (rx_mhz is null or tx_mhz is null or (acma_licence = '' and {q(p['licence'])} <> ''));")
        for i, f in enumerate(p.get('frequencies', [])):
            out.append('insert into meganet.station_frequency (station_id, ord, rx_mhz, tx_mhz, label, acma_licence, updated_by) '
                       f"values ({sid}, {i}, {q(f['rx_mhz'])}, {q(f['tx_mhz'])}, {q(f['label'])}, {q(f['acma_licence'])}, {S}) "
                       'on conflict (station_id, ord) do nothing;')
        out.append('')
    out.append("-- The rows that were on the wrong station come off it, through the editor's write path.")
    for s in plan['strip']:
        nets = "'[]'::jsonb" if s['clear_networks'] else "doc->'radio_network_ids'"
        out.append('select meganet.save_station(jsonb_set(jsonb_set(jsonb_set(doc - \'repeater\', \'{roles}\', (doc->\'roles\') - \'repeater\'), '
                   f"'{{radio_network_ids}}', {nets}), '{{notes}}', to_jsonb({append_note(DOC_NOTES, q(s['note']))})), updated_at) is not null as saved "
                   f"from meganet.station_json where id = {q(s['id'])} and doc ? 'repeater';")
    out.append('')
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--sql', action='store_true', required=True, help='print the SQL')
    ap.add_argument('--plan', default=PLAN)
    a = ap.parse_args(argv)
    with open(a.plan, encoding='utf-8') as fh:
        sys.stdout.write(render_sql(json.load(fh)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
